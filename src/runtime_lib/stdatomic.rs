/// Converts a C `__ATOMIC_*` memory ordering constant (integer 0–5) to a Rust
/// [`Ordering`] value suitable for passing to the atomic operation functions in
/// this module.
///
/// This delegates to [`crate::runtime_lib::atomic::c_memorder_to_rust`].
///
/// # C Constants
///
/// | Constant           | Value | Rust Equivalent     |
/// |--------------------|-------|---------------------|
/// | `__ATOMIC_RELAXED` |   0   | `Ordering::Relaxed` |
/// | `__ATOMIC_CONSUME` |   1   | `Ordering::Acquire` |
/// | `__ATOMIC_ACQUIRE` |   2   | `Ordering::Acquire` |
/// | `__ATOMIC_RELEASE` |   3   | `Ordering::Release` |
/// | `__ATOMIC_ACQ_REL` |   4   | `Ordering::AcqRel`  |
/// | `__ATOMIC_SEQ_CST` |   5   | `Ordering::SeqCst`  |
///
/// Out-of-range values default to `SeqCst` (strongest ordering) for safety.
#[inline]
pub(crate) fn convert_c_memorder(memorder: i32) -> Ordering {
    c_memorder_to_rust(memorder)
}

// ============================================================================
// Macro for generating atomic operation modules per data width
// ============================================================================

/// Generates a module containing all 13 C11 atomic operations for a given
/// atomic type and value width.
///
/// The generated module mirrors the C expansion of `ATOMIC_GEN(TYPE, SIZE)`
/// at `lib/stdatomic.c` lines 57–75:
///
/// ```text
/// ATOMIC_GEN(uint8_t, 1)   →  ops_1 module
/// ATOMIC_GEN(uint16_t, 2)  →  ops_2 module
/// ATOMIC_GEN(uint32_t, 4)  →  ops_4 module
/// ATOMIC_GEN(uint64_t, 8)  →  ops_8 module
/// ```
macro_rules! define_atomic_ops {
    (
        $mod_name:ident,
        $atomic_ty:ident,
        $val_ty:ty,
        $size:literal,
        $c_type:expr
    ) => {
        #[doc = concat!(
            "Atomic operations for `", stringify!($val_ty), "` values (",
            stringify!($size), "-byte width).\n\n",
            "C equivalent: `ATOMIC_GEN(", $c_type, ", ", stringify!($size),
            ")` expansion in `lib/stdatomic.c` (line 72–75).\n\n",
            "Each function performs one of the 13 C11 atomic read-modify-write\n",
            "operations using `std::sync::atomic::", stringify!($atomic_ty),
            "` hardware-backed methods."
        )]
        pub(crate) mod $mod_name {
            use std::sync::atomic::{$atomic_ty, Ordering};

            /// Atomic exchange — atomically stores `value` and returns the
            /// previous value.
            ///
            /// C equivalent: `__atomic_exchange_N(volatile void *atom, T value, int memorder)`
            /// where N = size suffix. Uses CAS loop: `OP = value`, `RET = cmp` (old).
            #[inline]
            pub(crate) fn exchange(
                atom: &$atomic_ty,
                value: $val_ty,
                order: Ordering,
            ) -> $val_ty {
                atom.swap(value, order)
            }

            /// Atomic add returning the **new** value (after addition).
            ///
            /// C equivalent: `__atomic_add_fetch_N` — `OP = (cmp + value)`, `RET = xchg` (new).
            /// Wrapping arithmetic matches C unsigned overflow semantics.
            #[inline]
            pub(crate) fn add_fetch(
                atom: &$atomic_ty,
                value: $val_ty,
                order: Ordering,
            ) -> $val_ty {
                atom.fetch_add(value, order).wrapping_add(value)
            }

            /// Atomic subtract returning the **new** value (after subtraction).
            ///
            /// C equivalent: `__atomic_sub_fetch_N` — `OP = (cmp - value)`, `RET = xchg` (new).
            /// Wrapping arithmetic matches C unsigned underflow semantics.
            #[inline]
            pub(crate) fn sub_fetch(
                atom: &$atomic_ty,
                value: $val_ty,
                order: Ordering,
            ) -> $val_ty {
                atom.fetch_sub(value, order).wrapping_sub(value)
            }

            /// Atomic bitwise AND returning the **new** value.
            ///
            /// C equivalent: `__atomic_and_fetch_N` — `OP = (cmp & value)`, `RET = xchg` (new).
            #[inline]
            pub(crate) fn and_fetch(
                atom: &$atomic_ty,
                value: $val_ty,
                order: Ordering,
            ) -> $val_ty {
                atom.fetch_and(value, order) & value
            }

            /// Atomic bitwise OR returning the **new** value.
            ///
            /// C equivalent: `__atomic_or_fetch_N` — `OP = (cmp | value)`, `RET = xchg` (new).
            #[inline]
            pub(crate) fn or_fetch(
                atom: &$atomic_ty,
                value: $val_ty,
                order: Ordering,
            ) -> $val_ty {
                atom.fetch_or(value, order) | value
            }

            /// Atomic bitwise XOR returning the **new** value.
            ///
            /// C equivalent: `__atomic_xor_fetch_N` — `OP = (cmp ^ value)`, `RET = xchg` (new).
            #[inline]
            pub(crate) fn xor_fetch(
                atom: &$atomic_ty,
                value: $val_ty,
                order: Ordering,
            ) -> $val_ty {
                atom.fetch_xor(value, order) ^ value
            }

            /// Atomic bitwise NAND returning the **new** value.
            ///
            /// C equivalent: `__atomic_nand_fetch_N` — `OP = ~(cmp & value)`, `RET = xchg` (new).
            /// NAND semantics: `!(old & value)` — bitwise NOT of (old AND value),
            /// matching the C expression `~(cmp & value)`.
            #[inline]
            pub(crate) fn nand_fetch(
                atom: &$atomic_ty,
                value: $val_ty,
                order: Ordering,
            ) -> $val_ty {
                let old = atom.fetch_nand(value, order);
                !(old & value)
            }

            /// Atomic add returning the **old** value (before addition).
            ///
            /// C equivalent: `__atomic_fetch_add_N` — `OP = (cmp + value)`, `RET = cmp` (old).
            #[inline]
            pub(crate) fn fetch_add(
                atom: &$atomic_ty,
                value: $val_ty,
                order: Ordering,
            ) -> $val_ty {
                atom.fetch_add(value, order)
            }

            /// Atomic subtract returning the **old** value (before subtraction).
            ///
            /// C equivalent: `__atomic_fetch_sub_N` — `OP = (cmp - value)`, `RET = cmp` (old).
            #[inline]
            pub(crate) fn fetch_sub(
                atom: &$atomic_ty,
                value: $val_ty,
                order: Ordering,
            ) -> $val_ty {
                atom.fetch_sub(value, order)
            }

            /// Atomic bitwise AND returning the **old** value.
            ///
            /// C equivalent: `__atomic_fetch_and_N` — `OP = (cmp & value)`, `RET = cmp` (old).
            #[inline]
            pub(crate) fn fetch_and(
                atom: &$atomic_ty,
                value: $val_ty,
                order: Ordering,
            ) -> $val_ty {
                atom.fetch_and(value, order)
            }

            /// Atomic bitwise OR returning the **old** value.
            ///
            /// C equivalent: `__atomic_fetch_or_N` — `OP = (cmp | value)`, `RET = cmp` (old).
            #[inline]
            pub(crate) fn fetch_or(
                atom: &$atomic_ty,
                value: $val_ty,
                order: Ordering,
            ) -> $val_ty {
                atom.fetch_or(value, order)
            }

            /// Atomic bitwise XOR returning the **old** value.
            ///
            /// C equivalent: `__atomic_fetch_xor_N` — `OP = (cmp ^ value)`, `RET = cmp` (old).
            #[inline]
            pub(crate) fn fetch_xor(
                atom: &$atomic_ty,
                value: $val_ty,
                order: Ordering,
            ) -> $val_ty {
                atom.fetch_xor(value, order)
            }

            /// Atomic bitwise NAND returning the **old** value.
            ///
            /// C equivalent: `__atomic_fetch_nand_N` — `OP = ~(cmp & value)`, `RET = cmp` (old).
            /// The NAND is applied atomically; this function returns the value that
            /// was present *before* the NAND was stored.
            #[inline]
            pub(crate) fn fetch_nand(
                atom: &$atomic_ty,
                value: $val_ty,
                order: Ordering,
            ) -> $val_ty {
                atom.fetch_nand(value, order)
            }
        }
    };
}

