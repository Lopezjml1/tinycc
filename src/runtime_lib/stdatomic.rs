/// Determines whether atomic operations for a given byte size are lock-free
/// on the current architecture.
///
/// C equivalent: `__atomic_is_lock_free(unsigned long size, const volatile void *ptr)`
/// at `lib/stdatomic.c` lines 84–100.
///
/// # Lock-Free Guarantees
///
/// | Size | 32-bit (i386/ARM) | 64-bit (x86_64/AArch64/RISC-V) |
/// |------|-------------------|---------------------------------|
/// |  1   | ✓ lock-free       | ✓ lock-free                     |
/// |  2   | ✓ lock-free       | ✓ lock-free                     |
/// |  4   | ✓ lock-free       | ✓ lock-free                     |
/// |  8   | ✗ NOT lock-free   | ✓ lock-free                     |
/// | >8   | ✗ NOT lock-free   | ✗ NOT lock-free                 |
///
/// On 32-bit architectures, 8-byte atomics require locking (e.g., i386 uses
/// `lock cmpxchg8b` which is lock-free but only for compare-exchange, not for
/// general-purpose atomic operations without CAS loops).
///
/// The `ptr` parameter from the C API is not needed in Rust — alignment is
/// guaranteed by the type system for `std::sync::atomic` types.
///
/// # Architecture Detection
///
/// Uses `cfg!()` macro for compile-time architecture detection, matching the
/// C preprocessor guards:
/// ```c
/// #if defined __x86_64__ || defined __aarch64__ || defined __riscv
///     case 8: ret = true; break;
/// #else
///     case 8: ret = false; break;
/// #endif
/// ```
pub(crate) fn is_lock_free(size: usize) -> bool {
    match size {
        1 | 2 | 4 => true,
        8 => {
            // 8-byte atomics are lock-free only on 64-bit architectures.
            // C: `#if defined __x86_64__ || defined __aarch64__ || defined __riscv`
            cfg!(any(
                target_arch = "x86_64",
                target_arch = "aarch64",
                target_arch = "riscv64"
            ))
        }
        _ => false,
    }
}

