/// Enum representing the 13 C11 atomic read-modify-write operations.
///
/// C equivalent: The 13 `ATOMIC_*` macro variants generated by `ATOMIC_GEN`
/// in `lib/stdatomic.c` (lines 57–70).
///
/// Each variant corresponds to one of the `__atomic_*` builtins that GCC and
/// TCC provide. The `*Fetch` variants return the **new** value (after the
/// operation), while the `Fetch*` variants return the **old** value (before
/// the operation). `Exchange` always returns the old value.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]
pub(crate) enum AtomicOp {
    /// Atomic exchange — stores new value, returns old value.
    /// C: `__atomic_exchange_N`
    Exchange,
    /// Atomic add returning **new** value.
    /// C: `__atomic_add_fetch_N`
    AddFetch,
    /// Atomic subtract returning **new** value.
    /// C: `__atomic_sub_fetch_N`
    SubFetch,
    /// Atomic bitwise AND returning **new** value.
    /// C: `__atomic_and_fetch_N`
    AndFetch,
    /// Atomic bitwise OR returning **new** value.
    /// C: `__atomic_or_fetch_N`
    OrFetch,
    /// Atomic bitwise XOR returning **new** value.
    /// C: `__atomic_xor_fetch_N`
    XorFetch,
    /// Atomic bitwise NAND returning **new** value.
    /// C: `__atomic_nand_fetch_N` — computes `~(old & value)`
    NandFetch,
    /// Atomic add returning **old** value.
    /// C: `__atomic_fetch_add_N`
    FetchAdd,
    /// Atomic subtract returning **old** value.
    /// C: `__atomic_fetch_sub_N`
    FetchSub,
    /// Atomic bitwise AND returning **old** value.
    /// C: `__atomic_fetch_and_N`
    FetchAnd,
    /// Atomic bitwise OR returning **old** value.
    /// C: `__atomic_fetch_or_N`
    FetchOr,
    /// Atomic bitwise XOR returning **old** value.
    /// C: `__atomic_fetch_xor_N`
    FetchXor,
    /// Atomic bitwise NAND returning **old** value.
    /// C: `__atomic_fetch_nand_N` — computes `~(old & value)`, returns old
    FetchNand,
}

