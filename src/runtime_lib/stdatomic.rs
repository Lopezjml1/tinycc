    /// Verify that different memory orderings work without panicking.
    #[test]
    fn test_memory_orderings() {
        let orderings = [
            Ordering::Relaxed,
            Ordering::Acquire,
            Ordering::Release,
            Ordering::AcqRel,
            Ordering::SeqCst,
        ];

        for &order in &orderings {
            let atom = AtomicU32::new(42);

            // exchange works with all orderings
            let _ = ops_4::exchange(&atom, 100, order);

            // fetch_add/sub work with all orderings
            let _ = ops_4::fetch_add(&atom, 1, order);
            let _ = ops_4::fetch_sub(&atom, 1, order);

            // bitwise ops work with all orderings
            let _ = ops_4::fetch_and(&atom, 0xFF, order);
            let _ = ops_4::fetch_or(&atom, 0x01, order);
            let _ = ops_4::fetch_xor(&atom, 0x01, order);
            let _ = ops_4::fetch_nand(&atom, 0xFF, order);
        }
    }
