    /// Verify wrapping arithmetic on overflow/underflow boundaries.
    #[test]
    fn test_wrapping_arithmetic() {
        // u8 overflow: 255 + 1 = 0 (wrapping)
        let atom8 = AtomicU8::new(255);
        assert_eq!(ops_1::add_fetch(&atom8, 1, Ordering::SeqCst), 0);
        assert_eq!(atom8.load(Ordering::SeqCst), 0);

        // u8 underflow: 0 - 1 = 255 (wrapping)
        assert_eq!(ops_1::sub_fetch(&atom8, 1, Ordering::SeqCst), 255);
        assert_eq!(atom8.load(Ordering::SeqCst), 255);

        // u16 overflow
        let atom16 = AtomicU16::new(u16::MAX);
        assert_eq!(ops_2::add_fetch(&atom16, 1, Ordering::SeqCst), 0);

        // u32 overflow
        let atom32 = AtomicU32::new(u32::MAX);
        assert_eq!(ops_4::add_fetch(&atom32, 1, Ordering::SeqCst), 0);

        // u64 overflow
        let atom64 = AtomicU64::new(u64::MAX);
        assert_eq!(ops_8::add_fetch(&atom64, 1, Ordering::SeqCst), 0);
    }

    /// Verify NAND semantics: `!(old & value)` matching C `~(cmp & value)`.
    #[test]
    fn test_nand_semantics() {
        // For u8: NAND(0xFF, 0xAA) = !(0xFF & 0xAA) = !(0xAA) = 0x55
        let atom = AtomicU8::new(0xFF);
        assert_eq!(ops_1::nand_fetch(&atom, 0xAA, Ordering::SeqCst), 0x55);
        assert_eq!(atom.load(Ordering::SeqCst), 0x55);

        // fetch_nand returns OLD, atom gets new value
        let atom = AtomicU8::new(0xFF);
        assert_eq!(ops_1::fetch_nand(&atom, 0xAA, Ordering::SeqCst), 0xFF);
        assert_eq!(atom.load(Ordering::SeqCst), 0x55);

        // NAND with 0x00: !(x & 0) = !(0) = all ones
        let atom32 = AtomicU32::new(0x1234_5678);
        assert_eq!(ops_4::nand_fetch(&atom32, 0x0000_0000, Ordering::SeqCst), 0xFFFF_FFFF);

        // NAND with all ones: !(x & 0xFFFFFFFF) = !x
        let atom32 = AtomicU32::new(0xDEAD_BEEF);
        assert_eq!(ops_4::nand_fetch(&atom32, 0xFFFF_FFFF, Ordering::SeqCst), !0xDEAD_BEEF);
    }

    /// Verify `is_lock_free` for various sizes.
    #[test]
    fn test_is_lock_free() {
        // Sizes 1, 2, 4 are always lock-free
        assert!(is_lock_free(1));
        assert!(is_lock_free(2));
        assert!(is_lock_free(4));

        // Size 8 depends on architecture
        #[cfg(any(target_arch = "x86_64", target_arch = "aarch64", target_arch = "riscv64"))]
        assert!(is_lock_free(8));

        #[cfg(not(any(target_arch = "x86_64", target_arch = "aarch64", target_arch = "riscv64")))]
        assert!(!is_lock_free(8));

        // Other sizes are never lock-free
        assert!(!is_lock_free(0));
        assert!(!is_lock_free(3));
        assert!(!is_lock_free(5));
        assert!(!is_lock_free(16));
        assert!(!is_lock_free(32));
        assert!(!is_lock_free(usize::MAX));
    }

