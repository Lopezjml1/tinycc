        assert_eq!(ops_8::exchange(&atom, 2_000_000_000, Ordering::SeqCst), 1_000_000_000);
        assert_eq!(ops_8::add_fetch(&atom, 500, Ordering::SeqCst), 2_000_000_500);
        assert_eq!(ops_8::fetch_add(&atom, 500, Ordering::SeqCst), 2_000_000_500);
