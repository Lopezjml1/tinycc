//! C11 `__atomic_*` operation wrappers for the TCC runtime library.
//!
//! Provides atomic read-modify-write operations implementing the complete set of
//! C11 atomic operations for 1, 2, 4, and 8-byte types.
//!
//! # C Equivalent
//!
//! `lib/stdatomic.c` (105 lines) — uses an `ATOMIC_GEN_OP` macro to generate
//! compare-and-swap (CAS) loop implementations of 13 atomic operations × 4 sizes
//! = 52 functions total, plus `__atomic_is_lock_free`.
//!
//! The original C implementation pattern:
//!
//! ```text
//! ATOMIC_GEN_OP(TYPE, MODE, NAME, OP, RET):
//!   TYPE __atomic_NAME_MODE(volatile void *atom, TYPE value, int memorder) {
//!       TYPE xchg, cmp;
//!       __atomic_load(atom, &cmp, __ATOMIC_RELAXED);
//!       do { xchg = OP; } while (!__atomic_compare_exchange(atom, &cmp, &xchg, ...));
//!       return RET;
//!   }
//! ```
//!
//! # Translation Strategy
//!
//! In Rust, the CAS loops in the C source map directly to `std::sync::atomic`
//! methods (`swap`, `fetch_add`, `fetch_sub`, `fetch_and`, `fetch_or`,
//! `fetch_xor`, `fetch_nand`) which compile to native hardware atomic
//! instructions on each supported architecture. The `*_fetch` variants
//! (returning the new value) compute the result from the `fetch_*` return
//! value (the old value) plus the operation's effect.
//!
//! # Operation Semantics
//!
//! | Operation    | C Macro (OP / RET)           | Returns | Rust Mapping              |
//! |-------------|------------------------------|---------|---------------------------|
//! | exchange    | `value` / `cmp`              | OLD     | `swap()`                  |
//! | `add_fetch`   | `cmp + value` / `xchg`       | NEW     | `fetch_add()` + wrapping  |
//! | `sub_fetch`   | `cmp - value` / `xchg`       | NEW     | `fetch_sub()` + wrapping  |
//! | `and_fetch`   | `cmp & value` / `xchg`       | NEW     | `fetch_and()` + bitwise   |
//! | `or_fetch`    | `cmp \| value` / `xchg`      | NEW     | `fetch_or()` + bitwise    |
//! | `xor_fetch`   | `cmp ^ value` / `xchg`       | NEW     | `fetch_xor()` + bitwise   |
//! | `nand_fetch`  | `~(cmp & value)` / `xchg`    | NEW     | `fetch_nand()` + bitwise  |
//! | `fetch_add`   | `cmp + value` / `cmp`        | OLD     | `fetch_add()`             |
//! | `fetch_sub`   | `cmp - value` / `cmp`        | OLD     | `fetch_sub()`             |
//! | `fetch_and`   | `cmp & value` / `cmp`        | OLD     | `fetch_and()`             |
//! | `fetch_or`    | `cmp \| value` / `cmp`       | OLD     | `fetch_or()`              |
//! | `fetch_xor`   | `cmp ^ value` / `cmp`        | OLD     | `fetch_xor()`             |
//! | `fetch_nand`  | `~(cmp & value)` / `cmp`     | OLD     | `fetch_nand()`            |
//!
//! # Safety
//!
//! No `unsafe` blocks — all operations use the safe `std::sync::atomic` API.
//! Per AAP §0.8.1: zero `unsafe` in safe code paths.

